import { createClient } from '@supabase/supabase-js';
import * as fs from 'fs';

const envContent = fs.readFileSync('.env.local', 'utf-8');
const envVars: Record<string, string> = {};
envContent.split('\n').forEach(line => {
  const trimmed = line.trim();
  if (trimmed && !trimmed.startsWith('#')) {
    const idx = trimmed.indexOf('=');
    if (idx !== -1) {
      envVars[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
    }
  }
});

const supabase = createClient(envVars.VITE_SUPABASE_URL, envVars.SUPABASE_SECRET_KEY);

async function executeSafeCleanup() {
  console.log('====================================================');
  console.log('STARTING PHASE 1 TEST-DATA CLEANUP & RECONCILIATION');
  console.log('====================================================\n');

  // STEP 1: Delete test order items
  console.log('--- Step 1: Deleting test order items ---');
  const { data: deletedItems, error: itemsErr } = await supabase
    .from('order_items')
    .delete()
    .neq('id', 'non-existent-id') // delete all 10 verified test order items
    .select('id, order_id, product_id, quantity');
  
  if (itemsErr) {
    console.error('Error deleting order_items:', itemsErr);
    return;
  }
  console.log(`Deleted ${deletedItems.length} test order_items.`);

  // STEP 2: Delete test orders
  console.log('\n--- Step 2: Deleting test orders ---');
  const testOrderIds = [
    'ord_0524f10d39664a3d8bd0093bf824b1ba',
    'ord_c69ee7e94ae2452d91ec14469b492f43',
    'ord_851cbb9a16164fd4a41e569304852ef4',
    'ord_0cafd009f7ca481f8fd0df6841512ac0',
    'ord_3572c9e3fbf14312b9caad38180daad1',
    'ord_6dc6c78487b041a7a2e94142d7654341',
    'ord_36bbb90863c74a17bd04c6d91295b75c',
    'ord_9d7344b242e243239c37adc8ee5bc9df',
    'ord_866ab87e10884daeb82610965dfef067',
    'ord_ad7d029383eb4d7fa915600c15ab3956'
  ];
  const { data: deletedOrders, error: ordersErr } = await supabase
    .from('orders')
    .delete()
    .in('id', testOrderIds)
    .select('id, order_number');
  
  if (ordersErr) {
    console.error('Error deleting orders:', ordersErr);
    return;
  }
  console.log(`Deleted ${deletedOrders.length} test orders:`, deletedOrders.map(o => o.order_number));

  // STEP 3: Delete test customers
  console.log('\n--- Step 3: Deleting test customers ---');
  const testCustomerIds = [
    'cust-55502f40dc',
    'cust-2763354b9b',
    'cust-d790f8dae1',
    'cust-5e5a97250b',
    'cust-9486ab4d6f',
    'cust-b0907ea4d5',
    'cust-4659a57f80',
    'cust-0c50dabf07',
    'cust-fc74899368'
  ];
  const { data: deletedCustomers, error: custErr } = await supabase
    .from('customers')
    .delete()
    .in('id', testCustomerIds)
    .select('id, email');
  
  if (custErr) {
    console.error('Error deleting customers:', custErr);
    return;
  }
  console.log(`Deleted ${deletedCustomers.length} test customers:`, deletedCustomers.map(c => c.email));

  // STEP 4: Delete inventory logs generated by test operations
  console.log('\n--- Step 4: Deleting test inventory_logs ---');
  const { data: deletedLogs, error: logsErr } = await supabase
    .from('inventory_logs')
    .delete()
    .neq('id', '00000000-0000-0000-0000-000000000000')
    .select('id, variant_id, reason');
  
  if (logsErr) {
    console.error('Error deleting inventory_logs:', logsErr);
    return;
  }
  console.log(`Deleted ${deletedLogs.length} test inventory logs.`);

  // STEP 5: Delete test audit logs for "shirt" and test orders
  console.log('\n--- Step 5: Deleting test audit logs ---');
  const testAuditIds = [
    '3f8a52b8-a662-4ec2-8c1a-02445c19cf1f', // CREATE_PRODUCT shirt
    'fefcaef5-02aa-45bf-bcc2-a46ba8f8fb90', // UPDATE_ORDER_STATUS
    'e9e6cb60-d858-4789-a43f-676acfd53b8f', // UPDATE_ORDER_STATUS
    'c180c972-d51b-4b67-aef5-377748d40689', // UPDATE_ORDER_STATUS
    'f7cd5640-af07-40c6-9b7b-acd41b0f8151', // UPDATE_ORDER_STATUS
    '45bf39c6-8dbd-44d1-bf53-4301bc2adb01'  // UPDATE_ORDER_STATUS
  ];
  const { data: deletedAudits, error: auditErr } = await supabase
    .from('audit_logs')
    .delete()
    .in('id', testAuditIds)
    .select('id, action, details');
  
  if (auditErr) {
    console.error('Error deleting audit logs:', auditErr);
  } else {
    console.log(`Deleted ${deletedAudits.length} test audit log entries.`);
  }

  // STEP 6: Delete test variants for "shirt"
  console.log('\n--- Step 6: Deleting 4 variants for test product "shirt" ---');
  const testVariantIds = [
    'shirt-standard-s',
    'shirt-standard-m',
    'shirt-standard-l',
    'shirt-standard-xl'
  ];
  const { data: deletedVariants, error: varErr } = await supabase
    .from('product_variants')
    .delete()
    .in('id', testVariantIds)
    .select('id, sku');
  
  if (varErr) {
    console.error('Error deleting product_variants:', varErr);
    return;
  }
  console.log(`Deleted ${deletedVariants.length} test product_variants:`, deletedVariants.map(v => v.id));

  // STEP 7: Delete test product "shirt"
  console.log('\n--- Step 7: Deleting test product "shirt" ---');
  const { data: deletedProduct, error: prodErr } = await supabase
    .from('products')
    .delete()
    .eq('id', 'shirt')
    .select('id, name');
  
  if (prodErr) {
    console.error('Error deleting product shirt:', prodErr);
    return;
  }
  console.log(`Deleted product:`, deletedProduct);

  // STEP 8: Reconcile legitimate variant inventory
  console.log('\n--- Step 8: Reconciling legitimate product and variant inventory ---');
  const variantUpdates = [
    { id: 'modern-bandhgala-kurta-terracotta-rust-s', stock: 15 },
    { id: 'modern-bandhgala-kurta-terracotta-rust-m', stock: 15 },
    { id: 'modern-bandhgala-kurta-terracotta-rust-xl', stock: 15 },
    { id: 'sandstone-nehru-jacket-champagne-sand-m', stock: 15 },
    { id: 'essential-cotton-t-shirt-ivory-m', stock: 15 },
    { id: 'essential-cotton-t-shirt-ivory-l', stock: 15 }
  ];

  for (const vu of variantUpdates) {
    const { error: vuErr } = await supabase
      .from('product_variants')
      .update({ stock: vu.stock, in_stock: true })
      .eq('id', vu.id);
    if (vuErr) {
      console.error(`Failed to update variant ${vu.id}:`, vuErr);
    } else {
      console.log(`  Restored variant ${vu.id} to stock = ${vu.stock}`);
    }
  }

  // Update parent product total_stock
  const productStockUpdates = [
    { id: 'modern-bandhgala-kurta', total_stock: 150 },
    { id: 'sandstone-nehru-jacket', total_stock: 120 },
    { id: 'essential-cotton-t-shirt', total_stock: 180 }
  ];

  for (const pu of productStockUpdates) {
    const { error: puErr } = await supabase
      .from('products')
      .update({ total_stock: pu.total_stock })
      .eq('id', pu.id);
    if (puErr) {
      console.error(`Failed to update product ${pu.id}:`, puErr);
    } else {
      console.log(`  Restored product ${pu.id} to total_stock = ${pu.total_stock}`);
    }
  }

  console.log('\n====================================================');
  console.log('CLEANUP & RECONCILIATION COMPLETED SUCCESSFULLY');
  console.log('====================================================\n');
}

executeSafeCleanup();

